package cl.almejo.vsim.ui.tools;

/**
 * What a press on the canvas would do here, as a cursor (spec §5.3): DEFAULT select or rubber band, MOVE move the
 * selection or pan, CROSSHAIR start a wire or place a component, HAND toggle an interactive component.
 */
public enum CanvasCursor { DEFAULT, MOVE, CROSSHAIR, HAND }
